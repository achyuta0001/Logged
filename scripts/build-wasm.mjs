#!/usr/bin/env node
// Compiles the WebAssembly surface kernel (src/sim/wasm/surface.as.ts, AssemblyScript) and embeds the
// module, base64, in src/sim/wasm/surface.bin.ts. The engine imports that file like any other module:
// no fetch and no asset URL, so it loads the same way in the dev worker, in the production bundle under
// its base path (/Logged/), in node (tests, calibrate.mjs), and synchronously (SimCore stays sync).
//
//   npm run wasm                         rebuild after editing surface.as.ts
//   node scripts/build-wasm.mjs --check  exit 1 when surface.bin.ts is not what the source compiles to
//                                        (npm test runs the same check: src/sim/__tests__/wasm.test.ts)
//
// The compiler (assemblyscript, Apache-2.0) is a pinned devDependency; the output is deterministic for
// one compiler version, which surface.bin.ts records.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const SOURCE = path.join(ROOT, 'src/sim/wasm/surface.as.ts');
export const TARGET = path.join(ROOT, 'src/sim/wasm/surface.bin.ts');

/** compiler flags: optimised, no runtime or assertions, memory provided by src/sim/kernel.ts */
const FLAGS = ['-O3', '--noAssert', '--runtime', 'stub', '--importMemory', '--initialMemory', '0', '--noExportMemory'];

/** compile the kernel; resolves to { bytes, version } */
export async function compileSurface() {
  const { default: asc } = await import('assemblyscript/asc');
  const out = {};
  const stderr = asc.createMemoryStream();
  const res = await asc.main([path.relative(ROOT, SOURCE), '--outFile', 'surface.wasm', ...FLAGS], {
    stdout: asc.createMemoryStream(),
    stderr,
    readFile: (name, baseDir) => {
      const p = path.resolve(ROOT, baseDir, name);
      return fs.existsSync(p) ? fs.readFileSync(p, 'utf8') : null;
    },
    writeFile: (name, contents) => { out[path.basename(name)] = contents; },
    listFiles: () => [],
  });
  if (res.error) throw new Error(`asc failed: ${res.error.message}\n${stderr.toString()}`);
  const bytes = out['surface.wasm'];
  if (!bytes) throw new Error('asc wrote no surface.wasm');
  return { bytes: Uint8Array.from(bytes), version: asc.version };
}

/** text of surface.bin.ts for a compiled module */
export function renderModule(bytes, version, sourceText) {
  const sha = crypto.createHash('sha256').update(sourceText).digest('hex');
  return [
    `// Generated by scripts/build-wasm.mjs (\`npm run wasm\`) from surface.as.ts with AssemblyScript ${version}. Do not edit.`,
    '// npm test fails when this is not what the source compiles to (src/sim/__tests__/wasm.test.ts).',
    `/** sha-256 of surface.as.ts */`,
    `export const SURFACE_SOURCE_SHA256 = '${sha}';`,
    `/** the compiled module (${bytes.length} bytes), base64 */`,
    `export const SURFACE_WASM =\n  '${Buffer.from(bytes).toString('base64')}';`,
    '',
  ].join('\n');
}

/** what surface.bin.ts should hold, and what it holds */
export async function expectedModuleText() {
  const { bytes, version } = await compileSurface();
  return {
    expected: renderModule(bytes, version, fs.readFileSync(SOURCE, 'utf8')),
    actual: fs.existsSync(TARGET) ? fs.readFileSync(TARGET, 'utf8') : '',
    bytes: bytes.length,
  };
}

async function main() {
  const { expected, actual, bytes } = await expectedModuleText();
  const rel = path.relative(ROOT, TARGET);
  if (process.argv.includes('--check')) {
    if (expected !== actual) {
      console.error(`${rel} is out of date with surface.as.ts: run npm run wasm`);
      process.exit(1);
    }
    console.log(`${rel} is up to date (${bytes} bytes)`);
    return;
  }
  if (expected === actual) console.log(`${rel} unchanged (${bytes} bytes)`);
  else {
    fs.writeFileSync(TARGET, expected);
    console.log(`wrote ${rel} (${bytes} bytes of WebAssembly)`);
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) await main();
